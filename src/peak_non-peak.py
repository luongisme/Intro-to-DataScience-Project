import matplotlib.pyplot as plt
import seaborn as sns
from main import orders

peak_season = ['2016-01-01', '2016-02-05', '2016-02-06', '2016-02-07',
            '2016-02-08', '2016-02-09', '2016-02-10', '2016-03-27',
            '2016-05-08', '2016-06-12', '2016-08-14', '2016-10-12',
            '2016-11-11', '2016-11-25', '2016-11-28', '2016-12-25',
            '2016-12-31',

            '2017-01-01', '2017-02-24', '2017-02-25', '2017-02-26',
            '2017-02-27', '2017-02-28', '2017-03-01', '2017-04-16',
            '2017-05-14', '2017-06-12', '2017-08-13', '2017-10-12',
            '2017-11-11', '2017-11-24', '2017-11-27', '2017-12-25',
            '2017-12-31',

            '2018-01-01', '2018-02-09', '2018-02-10', '2018-02-11',
            '2018-02-12', '2018-02-13', '2018-02-14', '2018-04-01',
            '2018-05-13', '2018-06-12', '2018-08-12', '2018-10-12',
            '2018-11-11', '2018-11-23', '2018-11-26', '2018-12-25',
            '2018-12-31']

orders['season'] = orders['order_approved_at'].dt.date.apply(lambda x: 'Peak' if x in peak_season else 'Non-peak')
rate = orders.groupby('season')['is_late'].mean() * 100
print(rate)

plt.figure(figsize=(8, 5))
sns.barplot(x = rate.index, y = rate.values)
plt.xlabel('Season')
plt.ylabel('Late order rate (%)')
plt.title('Late order rate (%) by season')
plt.show()