from typing import Any, Dict
from pathlib import Path

import pandas as pd

from src.paths import RAW_DIR, INTERIM_DIR


# Raw datasets
DATASETS: Dict[str, str] = {
    "customers": "olist_customers_dataset.csv",
    "geolocation": "olist_geolocation_dataset.csv",
    "order_items": "olist_order_items_dataset.csv",
    "payments": "olist_order_payments_dataset.csv",
    "reviews": "olist_order_reviews_dataset.csv",
    "orders": "olist_orders_dataset.csv",
    "products": "olist_products_dataset.csv",
    "sellers": "olist_sellers_dataset.csv",
    "category_translation": "product_category_name_translation.csv",
}


# Intermediate datasets generated by the pipeline
INTERIM_DATASETS: Dict[str, str] = {
    "merged_order_items": "merged_order_items.parquet",
}


def load_data(
    name: str,
    stage: str = "raw",
    **kwargs: Any,
) -> pd.DataFrame:
    """Load a registered dataset from raw or interim storage.

    Args:
        name: Registered dataset name.
        stage: Data stage: "raw" or "interim".
        **kwargs: Additional arguments forwarded to pandas reader.

    Returns:
        pd.DataFrame: Loaded dataset.

    Raises:
        ValueError: If stage or dataset name is invalid.
        FileNotFoundError: If the dataset file does not exist.
    """

    if stage == "raw":
        registry = DATASETS
        data_dir = RAW_DIR

    elif stage == "interim":
        registry = INTERIM_DATASETS
        data_dir = INTERIM_DIR

    else:
        raise ValueError(
            f"Unknown stage '{stage}'. "
            "Available stages: ['raw', 'interim']"
        )

    if name not in registry:
        raise ValueError(
            f"Unknown dataset '{name}' in stage '{stage}'. "
            f"Available datasets: {list(registry.keys())}"
        )

    path: Path = data_dir / registry[name]

    if not path.exists():
        raise FileNotFoundError(
            f"Dataset not found: '{path}'."
        )

    # Select the correct pandas reader
    if path.suffix == ".csv":
        return pd.read_csv(path, **kwargs)

    elif path.suffix == ".parquet":
        return pd.read_parquet(path, **kwargs)

    else:
        raise ValueError(
            f"Unsupported file format: '{path.suffix}'"
        )


def load_all():
    """Load all registered raw datasets."""
    return {
        name: load_data(name)
        for name in DATASETS
    }